-- Mark dictionary entries that are ʻŌlelo Hawaiʻi words or phrases, as opposed to Pidgin.
--
-- Until now the only signal was free text in `origin` ("Directly from the Hawaiian language...",
-- "A Hawaiian word.", "Hawaiian"), which the translator pattern-matched and mostly missed. A real
-- column lets the dictionary show an ʻŌlelo Hawaiʻi badge and lets the translator keep Hawaiian
-- words out of Pidgin output ("good" -> "maika'i").
--
-- Rule used: 'hawaiian' = the headword itself is Hawaiian, including Hawaiian compounds
-- (pau hana, tutu kane, mauka makai). Pidgin phrases containing a Hawaiian word stay 'pidgin'
-- ("I hele to da hale", "stay pono", "poi dog"). Drafted 2026-10-02 from 799 rows; 215 marked.
--
-- Each update is keyed on id AND headword, so a row that was edited since the draft is skipped
-- rather than mislabelled. New rows default to 'pidgin'; the admin add flow should set it.

ALTER TABLE public.dictionary_entries
    ADD COLUMN IF NOT EXISTS source_language text NOT NULL DEFAULT 'pidgin'
    CONSTRAINT dictionary_entries_source_language_check CHECK (source_language IN ('pidgin', 'hawaiian'));

